// ---------- language ----------
let lang = null;
const listeners = [];
function pick() {
  const saved = store("crackler.lang");
  if (saved && DICT[saved]) return saved;
  const nav = typeof navigator !== "undefined" && navigator.language ? navigator.language.toLowerCase() : "en";
  return nav.startsWith("it") ? "it" : "en";
}
function getLang() {
  return lang || (lang = pick());
}
function t(key, params) {
  let s = DICT[getLang()][key] ?? DICT.en[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
  return s;
}
function setLang(l) {
  if (!DICT[l]) return;
  lang = l;
  store("crackler.lang", l);
  applyI18n();
  listeners.forEach((fn) => fn(l));
}
function onLangChange(fn) {
  listeners.push(fn);
}

// ---------- markup ----------
function applyI18n(root = document) {
  document.documentElement.lang = getLang();
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-aria]"))
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
}

export { DICT, t, getLang, setLang, onLangChange, applyI18n };
